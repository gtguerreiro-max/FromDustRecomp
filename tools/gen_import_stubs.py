"""Generate runtime/kernel/imports_stubs.cpp: a logging stub for every kernel /
XAM function import that has no KFUNC(...) implementation in runtime/.

Usage: python gen_import_stubs.py   (run after list_imports.py --json)
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNTIME = os.path.join(ROOT, "runtime")
OUT = os.path.join(RUNTIME, "kernel", "imports_stubs.cpp")


def main():
    imports = json.load(open(os.path.join(ROOT, "config", "imports.json")))["functions"]
    implemented = set()
    for dirpath, _, files in os.walk(RUNTIME):
        for name in files:
            path = os.path.join(dirpath, name)
            if name.endswith(".cpp") and path != OUT:
                implemented.update(re.findall(r"\bKFUNC\((\w+)\)", open(path, encoding="utf-8").read()))

    missing = sorted(n for n in imports if n not in implemented)
    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by tools/gen_import_stubs.py - do not edit.\n")
        f.write("// Exports without a real implementation yet: log once, return 0.\n\n")
        f.write('#include "kernel.h"\n\n')
        for name in missing:
            f.write('KFUNC(%s) { kernel::LogUnimplemented("%s"); RETURN(0); }\n' % (name, name))
    print("%d implemented, %d stubbed" % (len(imports) - len(missing), len(missing)))


if __name__ == "__main__":
    main()
